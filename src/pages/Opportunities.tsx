import { useEffect, useMemo, useState } from "react";
import { useSearchParams } from "react-router-dom";
import { Bookmark, ExternalLink, MapPin, Search, Sparkles } from "lucide-react";
import { useWallet } from "../hooks/useWallet";
import { fetchByRecipient, isDeployed } from "../lib/contract";
import { verifiedSkills } from "../lib/score";
import { safeUrl, short } from "../lib/utils";
import { signedStoreRequest } from "../lib/signedStore";
import type { Opportunity, PlanStatus, SavedItem } from "../types";
import { Notice, Spinner } from "../components/ui";

const CATS = ["workshop", "hackathon", "course", "internship", "community"];
const PROMPTS = ["Beginner Solidity courses", "Blockchain hackathons this month", "Web3 workshops near me", "Open-source projects for students"];

export default function Opportunities() {
  const w = useWallet();
  const [sp] = useSearchParams();
  const [city, setCity] = useState(() => localStorage.getItem("ss_city") ?? "");
  const [interest, setInterest] = useState(sp.get("interest") ?? "Solidity");
  const [level, setLevel] = useState("beginner");
  const [cats, setCats] = useState<string[]>(["workshop", "hackathon", "course"]);
  const [freeOnly, setFreeOnly] = useState(true);
  const [onlineOnly, setOnlineOnly] = useState(false);
  const [skills, setSkills] = useState<string[]>([]);
  const [results, setResults] = useState<Opportunity[]>([]);
  const [meta, setMeta] = useState<{ live: boolean; note?: string } | null>(null);
  const [loading, setLoading] = useState(false);
  const [err, setErr] = useState<string | null>(null);
  const [saved, setSaved] = useState<Record<string, SavedItem>>({});

  useEffect(() => { // verified skills from the chain (read-only, used to personalize)
    if (w.address && isDeployed) fetchByRecipient(w.address).then((c) => setSkills(verifiedSkills(c).filter((s) => s.verified).map((s) => s.skill))).catch(() => undefined);
  }, [w.address]);
  useEffect(() => {
    if (!w.address) return;
    w.getSigner().then((signer) => signedStoreRequest(w.address!, signer, "GET")).then((d) => setSaved(d.saved ?? {})).catch((e) => setErr(`Saved plans require a wallet signature: ${(e as Error).message}`));
  }, [w.address]);

  const persist = (next: Record<string, SavedItem>) => {
    setSaved(next);
    if (w.address) w.getSigner().then((signer) => signedStoreRequest(w.address!, signer, "PUT", next)).catch((e) => setErr(`Could not save: ${(e as Error).message}`));
  };

  const search = async (q?: string) => {
    setLoading(true); setErr(null);
    try {
      const r = await fetch("/api/opportunities", { method: "POST", headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ city, interest: q ?? interest, level, categories: cats, freeOnly, onlineOnly, verifiedSkills: skills }) });
      const d = await r.json();
      if (!r.ok) throw new Error(d.error ?? "Search failed");
      setResults(d.results); setMeta({ live: d.live, note: d.note });
    } catch (e) { setErr((e as Error).message + " (is the server running? npm run server)"); }
    finally { setLoading(false); }
  };

  const geolocate = () => navigator.geolocation.getCurrentPosition(
    async (p) => {
      try {
        const r = await fetch(`https://nominatim.openstreetmap.org/reverse?format=jsonv2&lat=${p.coords.latitude}&lon=${p.coords.longitude}&zoom=10&addressdetails=1`);
        if (!r.ok) throw new Error("Reverse geocoding failed");
        const d = await r.json();
        const a = d.address || {};
        const detected = [a.city || a.town || a.village || a.county, a.state, a.country].filter(Boolean).join(", ");
        if (!detected) throw new Error("No city found");
        setCity(detected); localStorage.setItem("ss_city", detected); setErr(null);
      } catch { setErr("Could not detect a city from your location. Type your city instead."); }
    },
    () => setErr("Location permission denied. Type your city instead."), { enableHighAccuracy: false, timeout: 10000, maximumAge: 300000 });

  const savedList = useMemo(() => Object.values(saved), [saved]);

  return (
    <div className="grid gap-8 lg:grid-cols-[1fr_320px]">
      <div className="space-y-5">
        <div><h1 className="text-3xl">Opportunity Compass</h1>
          <p className="text-sm"><a className="underline" href="/assistant">Open Learning Assistant &amp; Roadmap Generator</a> · <a className="underline" href="/skills">Manage self-declared skills</a></p>
          <p className="text-sm text-muted">Results come from live web search and are links to follow, not endorsements. Suggestions and match reasons are generated by SkillStamp rules, not credentials.</p></div>
        {skills.length > 0 && <Notice kind="info">Verified skills from your passport used for matching: {skills.join(", ")}.</Notice>}
        <div className="flex flex-wrap gap-2">{PROMPTS.map((p) => <button key={p} className="btn-ghost" onClick={() => { setInterest(p); search(p); }}><Sparkles size={14} />{p}</button>)}</div>
        <form className="card grid gap-3 sm:grid-cols-2" onSubmit={(e) => { e.preventDefault(); localStorage.setItem("ss_city", city); search(); }}>
          <div><label className="label" htmlFor="i">Interest</label><input id="i" className="input" value={interest} onChange={(e) => setInterest(e.target.value)} /></div>
          <div><label className="label" htmlFor="c">City (optional)</label><input id="c" className="input" value={city} onChange={(e) => setCity(e.target.value)} placeholder="Pune, Maharashtra" /></div>
          <div><label className="label" htmlFor="l">Level</label><select id="l" className="input" value={level} onChange={(e) => setLevel(e.target.value)}><option>beginner</option><option>intermediate</option><option>advanced</option></select></div>
          <div className="flex items-end gap-3 text-sm">
            <label><input type="checkbox" checked={freeOnly} onChange={(e) => setFreeOnly(e.target.checked)} /> Free</label>
            <label><input type="checkbox" checked={onlineOnly} onChange={(e) => setOnlineOnly(e.target.checked)} /> Online only</label>
          </div>
          <div className="flex flex-wrap gap-2 sm:col-span-2">{CATS.map((c) => (
            <label key={c} className={`rounded-full border px-3 py-1 text-sm ${cats.includes(c) ? "border-sage bg-eucalyptus" : "border-sand"}`}>
              <input className="sr-only" type="checkbox" checked={cats.includes(c)} onChange={() => setCats(cats.includes(c) ? cats.filter((x) => x !== c) : [...cats, c])} />{c}</label>))}</div>
          <div className="flex gap-2 sm:col-span-2">
            <button className="btn" type="submit" disabled={loading || !interest.trim()}><Search size={14} /> Search</button>
            <button className="btn-ghost" type="button" onClick={geolocate}><MapPin size={14} /> Use my location (asks permission)</button>
            {city && <button className="btn-ghost" type="button" onClick={() => { setCity(""); localStorage.removeItem("ss_city"); }}>Clear city</button>}
          </div>
        </form>
        {loading && <Spinner text="Searching live sources…" />}
        {err && <Notice kind="error">{err} <button className="underline" onClick={() => search()}>Retry</button></Notice>}
        {meta && !meta.live && <Notice kind="warn">{meta.note} The items below are curated evergreen resources, not live search results.</Notice>}
        {meta?.live && results.length === 0 && <Notice kind="info">No results. Try another interest, or tick “Online only”.</Notice>}
        <ul className="space-y-3">{results.map((o) => (
          <li key={o.id} className="card space-y-2">
            <div className="flex flex-wrap items-center justify-between gap-2"><h2 className="text-lg">{o.title}</h2>
              <span className="rounded-full bg-sand px-2 py-0.5 text-xs">{o.source === "live-search" ? "Live search result" : "Curated evergreen"} · {o.category}</span></div>
            <p className="text-sm">{o.description}</p>
            <dl className="grid grid-cols-2 gap-1 text-xs text-muted sm:grid-cols-4">
              <div>Provider: {o.provider}</div><div>Location: {o.location}</div><div>Date: {o.date}</div><div>Price: {o.price}</div></dl>
            <p className="text-sm"><b>Why suggested (generated):</b> {o.whyRecommended}</p>
            <p className="text-xs text-muted">Checked {new Date(o.checkedAt).toLocaleDateString()}. Details such as dates and fees are not verified; confirm on the official page.</p>
            <div className="flex gap-2">
              <a className="btn" href={safeUrl(o.url)} target="_blank" rel="noopener noreferrer">Open source <ExternalLink size={14} /></a>
              <button className="btn-ghost" disabled={!w.address} title={w.address ? "" : "Connect wallet to save"} onClick={() => persist({ ...saved, [o.id]: { opp: o, status: "saved", savedAt: new Date().toISOString() } })}><Bookmark size={14} /> Save</button>
            </div>
          </li>))}</ul>
      </div>
      <aside className="space-y-3">
        <h2 className="text-xl">Saved &amp; learning plan</h2>
        {!w.address && <Notice kind="info">Connect your wallet to save opportunities (stored off-chain on the server).</Notice>}
        {savedList.length === 0 && w.address && <p className="text-sm text-muted">Nothing saved yet.</p>}
        {savedList.map((s) => (
          <div key={s.opp.id} className="card space-y-2 text-sm">
            <a className="underline" href={safeUrl(s.opp.url)} target="_blank" rel="noopener noreferrer">{s.opp.title}</a>
            <select className="input" aria-label="Status" value={s.status} onChange={(e) => persist({ ...saved, [s.opp.id]: { ...s, status: e.target.value as PlanStatus } })}>
              <option value="saved">Saved</option><option value="planned">Planned</option><option value="in_progress">In progress</option><option value="completed">Completed</option></select>
            {s.status === "completed" && <p className="text-xs text-muted">Marking complete does not create a credential. Ask an authorized issuer to issue one, and share your evidence hash with them.</p>}
            <button className="text-xs underline" onClick={() => { const n = { ...saved }; delete n[s.opp.id]; persist(n); }}>Remove</button>
          </div>))}
        {w.address && <p className="text-xs text-muted">Saved for {short(w.address)}. Wallet signature required to access or update saved plans.</p>}
      </aside>
    </div>
  );
}
